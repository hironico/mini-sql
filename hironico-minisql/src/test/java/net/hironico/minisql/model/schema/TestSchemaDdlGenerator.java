package net.hironico.minisql.model.schema;

import org.junit.Test;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

public class TestSchemaDdlGenerator {

    private static SchemaModel.Column col(String name, int pos, String type, String jdbc, int size, boolean nullable, boolean autoInc) {
        return new SchemaModel.Column(name, pos, type, jdbc, size, 0, nullable, autoInc, null);
    }

    /** CUSTOMER <- ORDERS <- ORDER_LINE, ORDER_LINE -> PRODUCT (not in the model), plus a view */
    static SchemaModel model() {
        Map<String, SchemaModel.Table> tables = new TreeMap<>();
        tables.put("ORDER_LINE", new SchemaModel.Table("TABLE",
                List.of(col("ORDER_ID", 1, "int4", "INTEGER", 10, false, false),
                        col("PRODUCT_ID", 2, "int4", "INTEGER", 10, true, false)),
                new SchemaModel.PrimaryKey("PK_LINE", List.of("ORDER_ID")),
                List.of(),
                List.of(new SchemaModel.ForeignKey("FK_LINE_ORDER", List.of("ORDER_ID"), "public", "ORDERS", List.of("ID"), "NO ACTION", "CASCADE"),
                        new SchemaModel.ForeignKey("FK_LINE_PRODUCT", List.of("PRODUCT_ID"), "public", "PRODUCT", List.of("ID"), "NO ACTION", "NO ACTION"))));
        tables.put("ORDERS", new SchemaModel.Table("TABLE",
                List.of(col("ID", 1, "int4", "INTEGER", 10, false, true),
                        col("CUSTOMER_ID", 2, "int4", "INTEGER", 10, true, false),
                        col("LABEL", 3, "varchar", "VARCHAR", 80, true, false)),
                new SchemaModel.PrimaryKey("PK_ORDERS", List.of("ID")),
                List.of(new SchemaModel.Index("PK_ORDERS", true, true, List.of(new SchemaModel.IndexColumn("ID", "ASC"))),
                        new SchemaModel.Index("IDX_ORDERS_CUST", false, false,
                                List.of(new SchemaModel.IndexColumn("CUSTOMER_ID", "ASC"), new SchemaModel.IndexColumn("LABEL", "DESC")))),
                List.of(new SchemaModel.ForeignKey("FK_ORDERS_CUSTOMER", List.of("CUSTOMER_ID"), "public", "CUSTOMER", List.of("ID"), "CASCADE", "SET NULL"))));
        tables.put("CUSTOMER", new SchemaModel.Table("TABLE",
                List.of(col("ID", 1, "int4", "INTEGER", 10, false, false)),
                new SchemaModel.PrimaryKey("PK_CUSTOMER", List.of("ID")), List.of(), List.of()));
        tables.put("V_ORDERS", new SchemaModel.Table("VIEW",
                List.of(col("ID", 1, "int4", "INTEGER", 10, true, false)), null, List.of(), List.of()));
        return new SchemaModel(1, "2026-01-01T00:00:00", new SchemaModel.Source("pg", "PostgreSQL", "16"), "public", tables);
    }

    private static List<String> all() {
        return new ArrayList<>(model().tables().keySet());
    }

    @Test
    public void testCreationOrderFollowsForeignKeysAndSkipsViews() {
        SchemaDdlGenerator gen = new SchemaDdlGenerator(model(), all(), new SchemaDdlGenerator.Options());
        assertEquals(List.of("CUSTOMER", "ORDERS", "ORDER_LINE"), gen.getCreationOrder());
        assertEquals(List.of("ORDER_LINE.FK_LINE_PRODUCT -> PRODUCT"), gen.getSkippedForeignKeys());
    }

    @Test
    public void testGenerateForOracle() {
        SchemaDdlGenerator.Options opt = new SchemaDdlGenerator.Options();
        opt.dialect = SqlDialect.ORACLE;
        opt.targetSchema = "APP";
        opt.dropTables = true;
        List<SchemaDdlGenerator.Statement> st = new SchemaDdlGenerator(model(), all(), opt).generate();

        assertEquals("3 drop(s), 3 table(s), 1 index(es), 2 foreign key(s)", SchemaDdlGenerator.summary(st));
        assertEquals("referencing tables dropped first", "DROP TABLE APP.ORDER_LINE CASCADE CONSTRAINTS", st.get(0).sql());

        String orders = st.stream().filter(s -> s.phase() == SchemaDdlGenerator.Phase.TABLE && s.tableName().equals("ORDERS"))
                .findFirst().orElseThrow().sql();
        assertEquals("CREATE TABLE APP.ORDERS (\n"
                + "    ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n"
                + "    CUSTOMER_ID NUMBER(10),\n"
                + "    LABEL VARCHAR2(80),\n"
                + "    CONSTRAINT PK_ORDERS PRIMARY KEY (ID)\n"
                + ")", orders);

        List<String> idx = st.stream().filter(s -> s.phase() == SchemaDdlGenerator.Phase.INDEX)
                .map(SchemaDdlGenerator.Statement::sql).toList();
        assertEquals("primary key index is not duplicated",
                List.of("CREATE INDEX APP.IDX_ORDERS_CUST ON APP.ORDERS (CUSTOMER_ID, LABEL DESC)"), idx);

        List<String> fks = st.stream().filter(s -> s.phase() == SchemaDdlGenerator.Phase.FOREIGN_KEY)
                .map(SchemaDdlGenerator.Statement::sql).toList();
        assertEquals("Oracle: no ON UPDATE",
                "ALTER TABLE APP.ORDERS ADD CONSTRAINT FK_ORDERS_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES APP.CUSTOMER (ID) ON DELETE SET NULL",
                fks.get(0));
        assertEquals("ALTER TABLE APP.ORDER_LINE ADD CONSTRAINT FK_LINE_ORDER FOREIGN KEY (ORDER_ID) REFERENCES APP.ORDERS (ID) ON DELETE CASCADE",
                fks.get(1));
    }

    @Test
    public void testQuotedSqlServerWithoutConstraintNames() {
        SchemaDdlGenerator.Options opt = new SchemaDdlGenerator.Options();
        opt.dialect = SqlDialect.SQLSERVER;
        opt.quoteIdentifiers = true;
        opt.keepConstraintNames = false;
        opt.foreignKeys = false;
        List<SchemaDdlGenerator.Statement> st = new SchemaDdlGenerator(model(), List.of("ORDERS"), opt).generate();

        assertEquals("CREATE TABLE [ORDERS] (\n"
                + "    [ID] INTEGER IDENTITY(1,1) NOT NULL,\n"
                + "    [CUSTOMER_ID] INTEGER NULL,\n"
                + "    [LABEL] VARCHAR(80) NULL,\n"
                + "    PRIMARY KEY ([ID])\n"
                + ")", st.get(0).sql());
        assertEquals("CREATE INDEX [ORDERS_IDX1] ON [ORDERS] ([CUSTOMER_ID], [LABEL] DESC)", st.get(1).sql());
        assertEquals(2, st.size());
    }

    @Test
    public void testScriptWithSeparators() {
        List<SchemaDdlGenerator.Statement> st = new SchemaDdlGenerator(model(), List.of("CUSTOMER"), new SchemaDdlGenerator.Options()).generate();

        String semicolon = SchemaDdlGenerator.toScript(st, ";");
        assertTrue(semicolon, semicolon.startsWith("-- Tables\nCREATE TABLE CUSTOMER ("));
        assertTrue(semicolon, semicolon.contains(");\n"));

        String go = SchemaDdlGenerator.toScript(st, "GO");
        assertTrue(go, go.contains(")\nGO\n"));
        assertFalse(go.contains(";"));
    }

    @Test
    public void testDefaultValuesOption() {
        Map<String, SchemaModel.Table> tables = new TreeMap<>();
        tables.put("T", new SchemaModel.Table("TABLE", List.of(
                new SchemaModel.Column("STATUS", 1, "varchar", "VARCHAR", 10, 0, true, false, "'NEW'"),
                new SchemaModel.Column("ID", 2, "int4", "INTEGER", 10, 0, false, false, "nextval('t_id_seq'::regclass)")),
                null, List.of(), List.of()));
        SchemaModel m = new SchemaModel(1, null, new SchemaModel.Source("x", "PostgreSQL", "16"), "public", tables);

        SchemaDdlGenerator.Options opt = new SchemaDdlGenerator.Options();
        opt.dialect = SqlDialect.POSTGRESQL;
        String withoutDefaults = new SchemaDdlGenerator(m, List.of("T"), opt).generate().get(0).sql();
        assertFalse(withoutDefaults.contains("DEFAULT"));

        opt.defaultValues = true;
        String withDefaults = new SchemaDdlGenerator(m, List.of("T"), opt).generate().get(0).sql();
        assertTrue(withDefaults, withDefaults.contains("STATUS varchar(10) DEFAULT 'NEW'"));
        assertFalse("sequence defaults are never copied", withDefaults.contains("nextval"));
    }
}
