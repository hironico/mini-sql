package net.hironico.minisql.model.schema;

import org.junit.Test;

import static org.junit.Assert.assertEquals;

public class TestSqlDialect {

    private static SchemaModel.Column col(String type, String jdbcType, Integer size, Integer scale) {
        return new SchemaModel.Column("C", 1, type, jdbcType, size, scale, true, false, null);
    }

    @Test
    public void testDetect() {
        assertEquals(SqlDialect.POSTGRESQL, SqlDialect.detect("PostgreSQL"));
        assertEquals(SqlDialect.ORACLE, SqlDialect.detect("Oracle"));
        assertEquals(SqlDialect.SQLSERVER, SqlDialect.detect("Microsoft SQL Server"));
        assertEquals(SqlDialect.SYBASE, SqlDialect.detect("Adaptive Server Enterprise"));
        assertEquals(SqlDialect.MYSQL, SqlDialect.detect("MariaDB"));
        assertEquals(SqlDialect.H2, SqlDialect.detect("H2"));
        assertEquals(SqlDialect.GENERIC, SqlDialect.detect(null));
        assertEquals(SqlDialect.GENERIC, SqlDialect.detect("SQLite"));
    }

    @Test
    public void testSameDatabaseKeepsNativeType() {
        SqlDialect pg = SqlDialect.POSTGRESQL;
        assertEquals("varchar(150)", pg.columnType(col("varchar", "VARCHAR", 150, 0), pg));
        assertEquals("numeric(12,2)", pg.columnType(col("numeric", "NUMERIC", 12, 2), pg));
        assertEquals("int4", pg.columnType(col("int4", "INTEGER", 10, 0), pg));
        assertEquals("text", pg.columnType(col("text", "VARCHAR", 2147483647, 0), pg));
        assertEquals("jsonb", pg.columnType(col("jsonb", "OTHER", 2147483647, 0), pg));
        assertEquals("timestamp", pg.columnType(col("timestamp", "TIMESTAMP", 29, 6), pg));
        // JTDS reports "int identity"
        assertEquals("int", SqlDialect.SYBASE.columnType(col("int identity", "INTEGER", 10, 0), SqlDialect.SYBASE));
        assertEquals("varchar(MAX)", SqlDialect.SQLSERVER.columnType(col("varchar", "VARCHAR", 2147483647, 0), SqlDialect.SQLSERVER));
    }

    @Test
    public void testOracleToPostgres() {
        SqlDialect pg = SqlDialect.POSTGRESQL;
        SqlDialect ora = SqlDialect.ORACLE;
        assertEquals("VARCHAR(80)", pg.columnType(col("VARCHAR2", "VARCHAR", 80, 0), ora));
        assertEquals("NUMERIC(10,2)", pg.columnType(col("NUMBER", "NUMERIC", 10, 2), ora));
        assertEquals("unbounded NUMBER", "NUMERIC", pg.columnType(col("NUMBER", "NUMERIC", 0, -127), ora));
        assertEquals("TEXT", pg.columnType(col("CLOB", "CLOB", 2147483647, 0), ora));
        assertEquals("BYTEA", pg.columnType(col("BLOB", "BLOB", 2147483647, 0), ora));
        assertEquals("TIMESTAMP", pg.columnType(col("DATE", "TIMESTAMP", 7, 0), ora));
    }

    @Test
    public void testPostgresToOracle() {
        SqlDialect ora = SqlDialect.ORACLE;
        SqlDialect pg = SqlDialect.POSTGRESQL;
        assertEquals("VARCHAR2(150)", ora.columnType(col("varchar", "VARCHAR", 150, 0), pg));
        assertEquals("CLOB", ora.columnType(col("text", "VARCHAR", 2147483647, 0), pg));
        assertEquals("NUMBER(10)", ora.columnType(col("int4", "INTEGER", 10, 0), pg));
        assertEquals("NUMBER(19)", ora.columnType(col("int8", "BIGINT", 19, 0), pg));
        assertEquals("NUMBER(1)", ora.columnType(col("bool", "BIT", 1, 0), pg));
        assertEquals("BINARY_DOUBLE", ora.columnType(col("float8", "DOUBLE", 17, 17), pg));
        assertEquals("BLOB", ora.columnType(col("bytea", "BINARY", 2147483647, 0), pg));
        assertEquals("vendor type kept as is", "uuid", ora.columnType(col("uuid", "OTHER", 2147483647, 0), pg));
    }

    @Test
    public void testOtherTargets() {
        SqlDialect pg = SqlDialect.POSTGRESQL;
        assertEquals("DATETIME2", SqlDialect.SQLSERVER.columnType(col("timestamp", "TIMESTAMP", 29, 6), pg));
        assertEquals("BIT", SqlDialect.SQLSERVER.columnType(col("bool", "BIT", 1, 0), pg));
        assertEquals("VARCHAR(MAX)", SqlDialect.SQLSERVER.columnType(col("text", "VARCHAR", 2147483647, 0), pg));
        assertEquals("DATETIME", SqlDialect.SYBASE.columnType(col("timestamp", "TIMESTAMP", 29, 6), pg));
        assertEquals("LONGTEXT", SqlDialect.MYSQL.columnType(col("text", "VARCHAR", 2147483647, 0), pg));
        assertEquals("DOUBLE PRECISION", SqlDialect.H2.columnType(col("float8", "DOUBLE", 17, 17), pg));
        assertEquals("DECIMAL(38,10)", SqlDialect.H2.columnType(col("numeric", "NUMERIC", 131089, 0), pg));
    }

    @Test
    public void testDialectRules() {
        assertEquals("IDENTITY(1,1)", SqlDialect.SQLSERVER.identityClause());
        assertEquals("AUTO_INCREMENT", SqlDialect.MYSQL.identityClause());
        assertEquals("GENERATED BY DEFAULT AS IDENTITY", SqlDialect.POSTGRESQL.identityClause());
        assertEquals("DROP TABLE T CASCADE CONSTRAINTS", SqlDialect.ORACLE.dropTable("T"));
        assertEquals("DROP TABLE T", SqlDialect.SQLSERVER.dropTable("T"));
        assertEquals(false, SqlDialect.ORACLE.supportsUpdateRule("CASCADE"));
        assertEquals(false, SqlDialect.ORACLE.supportsDeleteRule("SET DEFAULT"));
        assertEquals(true, SqlDialect.POSTGRESQL.supportsDeleteRule("SET DEFAULT"));
    }
}
