package net.hironico.minisql.ctrl;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import net.hironico.common.utils.json.JSONFile;
import net.hironico.minisql.model.SQLObject;
import net.hironico.minisql.model.SQLObjectTypeEnum;
import net.hironico.minisql.model.schema.SchemaModel;
import org.junit.AfterClass;
import org.junit.BeforeClass;
import org.junit.Test;

import java.sql.Connection;
import java.sql.DatabaseMetaData;
import java.sql.DriverManager;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertTrue;

/**
 * Tests the JSON model export against an in memory H2 database.
 */
public class TestSchemaModelExportCallable {

    private static Connection conn;

    @BeforeClass
    public static void setUp() throws Exception {
        conn = DriverManager.getConnection("jdbc:h2:mem:modelexport;DB_CLOSE_DELAY=-1");
        try (Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE SCHEMA SHOP");
            stmt.execute("CREATE SCHEMA OTHER");
            stmt.execute("CREATE TABLE SHOP.CUSTOMER ("
                    + " ID INTEGER GENERATED BY DEFAULT AS IDENTITY,"
                    + " EMAIL VARCHAR(150) NOT NULL,"
                    + " STATUS VARCHAR(10) DEFAULT 'NEW',"
                    + " CONSTRAINT PK_CUSTOMER PRIMARY KEY (ID))");
            stmt.execute("CREATE UNIQUE INDEX UK_CUSTOMER_EMAIL ON SHOP.CUSTOMER (EMAIL)");
            stmt.execute("CREATE TABLE SHOP.ORDER_LINE ("
                    + " ORDER_ID INTEGER NOT NULL,"
                    + " LINE_NO INTEGER NOT NULL,"
                    + " CUSTOMER_ID INTEGER,"
                    + " AMOUNT NUMERIC(12,2),"
                    + " CREATED TIMESTAMP,"
                    + " CONSTRAINT PK_ORDER_LINE PRIMARY KEY (ORDER_ID, LINE_NO),"
                    + " CONSTRAINT FK_LINE_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES SHOP.CUSTOMER (ID) ON DELETE CASCADE)");
            stmt.execute("CREATE INDEX IDX_LINE_CUST_DATE ON SHOP.ORDER_LINE (CUSTOMER_ID, CREATED DESC)");
            stmt.execute("CREATE VIEW SHOP.V_CUSTOMER AS SELECT ID, EMAIL FROM SHOP.CUSTOMER");
            stmt.execute("CREATE TABLE OTHER.PARAM (CODE VARCHAR(20) PRIMARY KEY)");
        }
    }

    @AfterClass
    public static void tearDown() throws Exception {
        conn.close();
    }

    private static SQLObject obj(String schema, String name, SQLObjectTypeEnum type) {
        SQLObject o = new SQLObject();
        o.schemaName = schema;
        o.name = name;
        o.type = type;
        return o;
    }

    private static List<SQLObject> shopObjects() {
        List<SQLObject> list = new ArrayList<>();
        // not sorted on purpose: the export must sort tables by name
        list.add(obj("SHOP", "V_CUSTOMER", SQLObjectTypeEnum.VIEW));
        list.add(obj("SHOP", "ORDER_LINE", SQLObjectTypeEnum.TABLE));
        list.add(obj("SHOP", "CUSTOMER", SQLObjectTypeEnum.TABLE));
        list.add(obj("SHOP", "SOME_PROC", SQLObjectTypeEnum.PROCEDURE));
        return list;
    }

    private static SchemaModel exportShop() throws Exception {
        DatabaseMetaData md = conn.getMetaData();
        List<SchemaModel> models = SchemaModelExportCallable.buildModels(md, shopObjects(), "test-h2");
        assertEquals(1, models.size());
        // serialize and parse back: the import tool will read the same records
        String json = SchemaModelExportCallable.toJson(models);
        return JSONFile.parse(json, SchemaModel.class);
    }

    @Test
    public void testDocumentHeaderAndTablesSortedByName() throws Exception {
        SchemaModel model = exportShop();

        assertEquals(SchemaModel.FORMAT_VERSION, model.formatVersion());
        assertNotNull(model.exportDate());
        assertEquals("test-h2", model.source().connection());
        assertEquals("H2", model.source().product());
        assertEquals("SHOP", model.schema());
        assertEquals("procedure must be ignored, tables sorted by name",
                List.of("CUSTOMER", "ORDER_LINE", "V_CUSTOMER"), new ArrayList<>(model.tables().keySet()));
    }

    @Test
    public void testColumns() throws Exception {
        SchemaModel model = exportShop();
        SchemaModel.Table customer = model.tables().get("CUSTOMER");
        assertEquals("TABLE", customer.type());

        List<SchemaModel.Column> cols = customer.columns();
        assertEquals(List.of("ID", "EMAIL", "STATUS"), cols.stream().map(SchemaModel.Column::name).toList());

        SchemaModel.Column id = cols.get(0);
        assertEquals(1, id.position());
        assertEquals("INTEGER", id.jdbcType());
        assertFalse(id.nullable());
        assertTrue(id.autoIncrement());

        SchemaModel.Column email = cols.get(1);
        assertEquals("VARCHAR", email.jdbcType());
        assertEquals(Integer.valueOf(150), email.size());
        assertFalse(email.nullable());
        assertNull(email.defaultValue());

        SchemaModel.Column status = cols.get(2);
        assertTrue(status.nullable());
        assertEquals("'NEW'", status.defaultValue());

        SchemaModel.Column amount = model.tables().get("ORDER_LINE").columns().get(3);
        assertEquals("NUMERIC", amount.jdbcType());
        assertEquals(Integer.valueOf(12), amount.size());
        assertEquals(Integer.valueOf(2), amount.scale());
    }

    @Test
    public void testPrimaryKeys() throws Exception {
        SchemaModel model = exportShop();

        SchemaModel.PrimaryKey pk = model.tables().get("CUSTOMER").primaryKey();
        assertEquals("PK_CUSTOMER", pk.name());
        assertEquals(List.of("ID"), pk.columns());

        SchemaModel.PrimaryKey composite = model.tables().get("ORDER_LINE").primaryKey();
        assertEquals("PK_ORDER_LINE", composite.name());
        assertEquals("columns in key order", List.of("ORDER_ID", "LINE_NO"), composite.columns());
    }

    @Test
    public void testIndexes() throws Exception {
        SchemaModel model = exportShop();

        List<SchemaModel.Index> customerIdx = model.tables().get("CUSTOMER").indexes();
        SchemaModel.Index uk = customerIdx.stream().filter(i -> i.name().equals("UK_CUSTOMER_EMAIL")).findFirst().orElseThrow();
        assertTrue(uk.unique());
        assertFalse(uk.primaryKey());
        assertEquals("EMAIL", uk.columns().get(0).name());
        assertTrue("the index backing the primary key must be flagged",
                customerIdx.stream().anyMatch(i -> i.primaryKey() && i.columns().get(0).name().equals("ID")));

        SchemaModel.Index composite = model.tables().get("ORDER_LINE").indexes().stream()
                .filter(i -> i.name().equals("IDX_LINE_CUST_DATE")).findFirst().orElseThrow();
        assertFalse(composite.unique());
        assertEquals(List.of("CUSTOMER_ID", "CREATED"), composite.columns().stream().map(SchemaModel.IndexColumn::name).toList());
        assertEquals("ASC", composite.columns().get(0).order());
        assertEquals("DESC", composite.columns().get(1).order());
    }

    @Test
    public void testForeignKeys() throws Exception {
        SchemaModel model = exportShop();
        assertTrue(model.tables().get("CUSTOMER").foreignKeys().isEmpty());

        List<SchemaModel.ForeignKey> fks = model.tables().get("ORDER_LINE").foreignKeys();
        assertEquals(1, fks.size());
        SchemaModel.ForeignKey fk = fks.get(0);
        assertEquals("FK_LINE_CUSTOMER", fk.name());
        assertEquals(List.of("CUSTOMER_ID"), fk.columns());
        assertEquals("SHOP", fk.referencedSchema());
        assertEquals("CUSTOMER", fk.referencedTable());
        assertEquals(List.of("ID"), fk.referencedColumns());
        assertEquals("CASCADE", fk.onDelete());
        assertNotNull(fk.onUpdate());
    }

    @Test
    public void testViewHasOnlyColumns() throws Exception {
        SchemaModel.Table view = exportShop().tables().get("V_CUSTOMER");
        assertEquals("VIEW", view.type());
        assertEquals(List.of("ID", "EMAIL"), view.columns().stream().map(SchemaModel.Column::name).toList());
        assertNull(view.primaryKey());
        assertTrue(view.indexes().isEmpty());
        assertTrue(view.foreignKeys().isEmpty());
    }

    @Test
    public void testSeveralSchemasGiveAnArray() throws Exception {
        List<SQLObject> objects = new ArrayList<>(shopObjects());
        objects.add(obj("OTHER", "PARAM", SQLObjectTypeEnum.TABLE));

        String json = SchemaModelExportCallable.toJson(
                SchemaModelExportCallable.buildModels(conn.getMetaData(), objects, "test-h2"));
        JsonNode root = new ObjectMapper().readTree(json);

        assertTrue(root.isArray());
        assertEquals(2, root.size());
        assertEquals("OTHER", root.get(0).get("schema").asText());
        assertEquals("SHOP", root.get(1).get("schema").asText());
        assertTrue(root.get(0).get("tables").has("PARAM"));

        JsonNode orderLine = root.get(1).get("tables").get("ORDER_LINE");
        for (String section : List.of("columns", "primaryKey", "indexes", "foreignKeys")) {
            assertTrue("missing section " + section, orderLine.has(section));
        }
    }

    @Test
    public void testRuleAndTypeNames() {
        assertEquals("CASCADE", SchemaModelExportCallable.ruleName((short) DatabaseMetaData.importedKeyCascade));
        assertEquals("SET NULL", SchemaModelExportCallable.ruleName((short) DatabaseMetaData.importedKeySetNull));
        assertEquals("SET DEFAULT", SchemaModelExportCallable.ruleName((short) DatabaseMetaData.importedKeySetDefault));
        assertEquals("RESTRICT", SchemaModelExportCallable.ruleName((short) DatabaseMetaData.importedKeyRestrict));
        assertEquals("NO ACTION", SchemaModelExportCallable.ruleName((short) DatabaseMetaData.importedKeyNoAction));
        assertEquals("VARCHAR", SchemaModelExportCallable.jdbcTypeName(java.sql.Types.VARCHAR));
        assertEquals("OTHER", SchemaModelExportCallable.jdbcTypeName(-123456));
    }
}
