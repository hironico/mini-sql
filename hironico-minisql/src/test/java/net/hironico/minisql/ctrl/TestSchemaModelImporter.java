package net.hironico.minisql.ctrl;

import net.hironico.minisql.model.SQLObject;
import net.hironico.minisql.model.SQLObjectTypeEnum;
import net.hironico.minisql.model.schema.SchemaDdlGenerator;
import net.hironico.minisql.model.schema.SchemaModel;
import net.hironico.minisql.model.schema.SchemaModelReader;
import net.hironico.minisql.model.schema.SqlDialect;
import org.junit.After;
import org.junit.Before;
import org.junit.Test;

import java.io.IOException;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.atomic.AtomicInteger;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

/**
 * Round trip test: export a schema of an H2 database, read the JSON back, import it in another schema
 * and export it again to compare both models.
 */
public class TestSchemaModelImporter {

    private Connection conn;

    @Before
    public void setUp() throws Exception {
        conn = DriverManager.getConnection("jdbc:h2:mem:modelimport_" + System.nanoTime() + ";DB_CLOSE_DELAY=-1");
        try (Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE SCHEMA SRC");
            stmt.execute("CREATE SCHEMA DST");
            stmt.execute("CREATE TABLE SRC.CUSTOMER ("
                    + " ID INTEGER GENERATED BY DEFAULT AS IDENTITY,"
                    + " EMAIL VARCHAR(150) NOT NULL,"
                    + " BALANCE NUMERIC(12,2),"
                    + " CONSTRAINT PK_CUSTOMER PRIMARY KEY (ID))");
            stmt.execute("CREATE UNIQUE INDEX UK_CUSTOMER_EMAIL ON SRC.CUSTOMER (EMAIL)");
            stmt.execute("CREATE TABLE SRC.ORDER_LINE ("
                    + " ORDER_ID INTEGER NOT NULL,"
                    + " LINE_NO INTEGER NOT NULL,"
                    + " CUSTOMER_ID INTEGER,"
                    + " CREATED TIMESTAMP,"
                    + " CONSTRAINT PK_ORDER_LINE PRIMARY KEY (ORDER_ID, LINE_NO),"
                    + " CONSTRAINT FK_LINE_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES SRC.CUSTOMER (ID) ON DELETE CASCADE)");
            stmt.execute("CREATE INDEX IDX_LINE_CUST_DATE ON SRC.ORDER_LINE (CUSTOMER_ID, CREATED DESC)");
            stmt.execute("CREATE VIEW SRC.V_CUSTOMER AS SELECT ID, EMAIL FROM SRC.CUSTOMER");
        }
    }

    @After
    public void tearDown() throws Exception {
        conn.close();
    }

    private static SQLObject obj(String schema, String name, SQLObjectTypeEnum type) {
        SQLObject o = new SQLObject();
        o.schemaName = schema;
        o.name = name;
        o.type = type;
        return o;
    }

    private SchemaModel export(String schema, String... tables) throws Exception {
        List<SQLObject> objects = new ArrayList<>();
        for (String t : tables) {
            objects.add(obj(schema, t, t.startsWith("V_") ? SQLObjectTypeEnum.VIEW : SQLObjectTypeEnum.TABLE));
        }
        String json = SchemaModelExportCallable.toJson(SchemaModelExportCallable.buildModels(conn.getMetaData(), objects, "h2"));
        return SchemaModelReader.parse(json).get(0);
    }

    private List<SchemaDdlGenerator.Statement> statements(SchemaModel model, boolean drop) {
        SchemaDdlGenerator.Options opt = new SchemaDdlGenerator.Options();
        opt.dialect = SqlDialect.H2;
        opt.targetSchema = "DST";
        opt.dropTables = drop;
        // H2 constraint names are unique per schema, keep them since the target schema is different
        return new SchemaDdlGenerator(model, model.tables().keySet(), opt).generate();
    }

    @Test
    public void testRoundTripRecreatesTheSameStructure() throws Exception {
        SchemaModel source = export("SRC", "CUSTOMER", "ORDER_LINE", "V_CUSTOMER");
        List<SchemaDdlGenerator.Statement> st = statements(source, false);
        assertEquals("the view is not re-created", "2 table(s), 2 index(es), 1 foreign key(s)", SchemaDdlGenerator.summary(st));

        AtomicInteger calls = new AtomicInteger();
        SchemaModelImporter.ImportResult result = new SchemaModelImporter(st).run(conn, (done, total, s, err) -> calls.incrementAndGet());

        assertFalse(result.failures().toString(), result.hasErrors());
        assertEquals(st.size(), result.executed());
        assertEquals(st.size(), calls.get());

        SchemaModel copy = export("DST", "CUSTOMER", "ORDER_LINE");
        for (String table : List.of("CUSTOMER", "ORDER_LINE")) {
            SchemaModel.Table src = source.tables().get(table);
            SchemaModel.Table dst = copy.tables().get(table);
            assertEquals(table + " columns", src.columns(), dst.columns());
            assertEquals(table + " primary key", src.primaryKey().columns(), dst.primaryKey().columns());
            assertEquals(table + " foreign keys", src.foreignKeys().stream().map(fk -> fk.name() + fk.columns() + fk.referencedTable() + fk.onDelete()).toList(),
                    dst.foreignKeys().stream().map(fk -> fk.name() + fk.columns() + fk.referencedTable() + fk.onDelete()).toList());
        }
        assertEquals("DST", copy.tables().get("ORDER_LINE").foreignKeys().get(0).referencedSchema());
        assertTrue(copy.tables().get("CUSTOMER").indexes().stream().anyMatch(i -> i.name().equals("UK_CUSTOMER_EMAIL") && i.unique()));
        assertTrue(copy.tables().get("ORDER_LINE").indexes().stream().anyMatch(i -> i.name().equals("IDX_LINE_CUST_DATE")
                && "DESC".equals(i.columns().get(1).order())));

        // the copy is usable: identity and cascade work
        try (Statement stmt = conn.createStatement()) {
            stmt.execute("INSERT INTO DST.CUSTOMER (EMAIL) VALUES ('a@b.c')");
            stmt.execute("INSERT INTO DST.ORDER_LINE (ORDER_ID, LINE_NO, CUSTOMER_ID) VALUES (1, 1, 1)");
            stmt.execute("DELETE FROM DST.CUSTOMER");
            try (ResultSet rs = stmt.executeQuery("SELECT COUNT(*) FROM DST.ORDER_LINE")) {
                rs.next();
                assertEquals(0, rs.getInt(1));
            }
        }
    }

    @Test
    public void testDropAndRecreate() throws Exception {
        SchemaModel source = export("SRC", "CUSTOMER", "ORDER_LINE");

        // first import: drop errors (tables do not exist yet) are not blocking
        SchemaModelImporter.ImportResult first = new SchemaModelImporter(statements(source, true)).run(conn, null);
        assertEquals(2, first.failures().size());
        assertFalse(first.hasErrors());
        assertFalse(first.stopped());

        SchemaModelImporter.ImportResult second = new SchemaModelImporter(statements(source, true)).run(conn, null);
        assertTrue(second.failures().isEmpty());
    }

    @Test
    public void testStopOrContinueOnError() throws Exception {
        SchemaModel source = export("SRC", "CUSTOMER", "ORDER_LINE");
        try (Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE TABLE DST.CUSTOMER (X INTEGER)");
        }

        SchemaModelImporter stopping = new SchemaModelImporter(statements(source, false));
        SchemaModelImporter.ImportResult stopped = stopping.run(conn, null);
        assertTrue(stopped.stopped());
        assertEquals(1, stopped.failures().size());
        assertEquals("CUSTOMER", stopped.failures().get(0).statement().tableName());
        assertEquals(0, stopped.executed());

        try (Statement stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE DST.ORDER_LINE IF EXISTS");
        }
        SchemaModelImporter continuing = new SchemaModelImporter(statements(source, false));
        continuing.setContinueOnError(true);
        SchemaModelImporter.ImportResult result = continuing.run(conn, null);
        assertFalse(result.stopped());
        assertTrue(result.hasErrors());
        assertTrue("ORDER_LINE is created even if CUSTOMER failed", result.executed() >= 1);
    }

    @Test
    public void testCancel() throws Exception {
        SchemaModel source = export("SRC", "CUSTOMER", "ORDER_LINE");
        SchemaModelImporter importer = new SchemaModelImporter(statements(source, false));
        SchemaModelImporter.ImportResult result = importer.run(conn, (done, total, s, err) -> importer.cancel());

        assertTrue(result.cancelled());
        assertEquals(1, result.executed());
    }

    @Test
    public void testReaderRejectsInvalidDocuments() {
        for (String json : List.of("", "{\"foo\": 1}", "[]", "not json",
                "{\"formatVersion\": 99, \"schema\": \"S\", \"tables\": {}}")) {
            try {
                SchemaModelReader.parse(json);
                fail("Document must be rejected: " + json);
            } catch (IOException ex) {
                // expected
            }
        }
    }
}
