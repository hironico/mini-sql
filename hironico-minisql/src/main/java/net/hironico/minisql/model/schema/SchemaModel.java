package net.hironico.minisql.model.schema;

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonProperty;

import java.util.List;
import java.util.Map;

/**
 * Portable description of the tables of a database schema, as produced by the "Export Model" action.
 * The same records are used to read the JSON document back, for instance to re-create the tables
 * into another database.
 * <p>
 * Structure: schema name, then tables by name, each table holding its columns, primary key,
 * indexes and foreign keys.
 *
 * @param formatVersion version of this document format, see {@link #FORMAT_VERSION}
 * @param exportDate    ISO local date time of the export
 * @param source        information about the source database
 * @param schema        name of the exported schema
 * @param tables        tables and views of the schema, by name (sorted)
 */
public record SchemaModel(
        @JsonProperty("formatVersion") int formatVersion,
        @JsonProperty("exportDate") String exportDate,
        @JsonProperty("source") Source source,
        @JsonProperty("schema") String schema,
        @JsonProperty("tables") Map<String, Table> tables) {

    /** Current version of the export document format */
    public static final int FORMAT_VERSION = 1;

    @JsonCreator
    public SchemaModel {
    }

    /**
     * Source database of the export.
     *
     * @param connection     name of the MiniSQL connection used for the export
     * @param product        database product name, from JDBC metadata
     * @param productVersion database product version, from JDBC metadata
     */
    public record Source(
            @JsonProperty("connection") String connection,
            @JsonProperty("product") String product,
            @JsonProperty("productVersion") String productVersion) {

        @JsonCreator
        public Source {
        }
    }

    /**
     * A table or a view.
     *
     * @param type        object type: TABLE, VIEW, MATERIALIZED VIEW...
     * @param columns     columns in table order
     * @param primaryKey  primary key, null if none
     * @param indexes     indexes sorted by name
     * @param foreignKeys foreign keys sorted by name
     */
    public record Table(
            @JsonProperty("type") String type,
            @JsonProperty("columns") List<Column> columns,
            @JsonProperty("primaryKey") PrimaryKey primaryKey,
            @JsonProperty("indexes") List<Index> indexes,
            @JsonProperty("foreignKeys") List<ForeignKey> foreignKeys) {

        @JsonCreator
        public Table {
        }
    }

    /**
     * A column of a table.
     *
     * @param name          column name
     * @param position      1 based position in the table
     * @param type          database specific type name (int4, VARCHAR2...)
     * @param jdbcType      portable java.sql.JDBCType name (INTEGER, VARCHAR...)
     * @param size          column size (length or precision)
     * @param scale         decimal digits
     * @param nullable      true if the column accepts NULL values
     * @param autoIncrement true if the value is generated by the database
     * @param defaultValue  default value expression, omitted if none
     */
    public record Column(
            @JsonProperty("name") String name,
            @JsonProperty("position") int position,
            @JsonProperty("type") String type,
            @JsonProperty("jdbcType") String jdbcType,
            @JsonProperty("size") Integer size,
            @JsonProperty("scale") Integer scale,
            @JsonProperty("nullable") boolean nullable,
            @JsonProperty("autoIncrement") boolean autoIncrement,
            @JsonInclude(JsonInclude.Include.NON_NULL)
            @JsonProperty("defaultValue") String defaultValue) {

        @JsonCreator
        public Column {
        }
    }

    /**
     * Primary key of a table.
     *
     * @param name    constraint name, may be null
     * @param columns column names in key order
     */
    public record PrimaryKey(
            @JsonProperty("name") String name,
            @JsonProperty("columns") List<String> columns) {

        @JsonCreator
        public PrimaryKey {
        }
    }

    /**
     * An index of a table.
     *
     * @param name       index name
     * @param unique     true for a unique index
     * @param primaryKey true if this index is the one backing the primary key constraint
     * @param columns    indexed columns in index order
     */
    public record Index(
            @JsonProperty("name") String name,
            @JsonProperty("unique") boolean unique,
            @JsonProperty("primaryKey") boolean primaryKey,
            @JsonProperty("columns") List<IndexColumn> columns) {

        @JsonCreator
        public Index {
        }
    }

    /**
     * A column of an index.
     *
     * @param name  column name or expression, as reported by the driver
     * @param order ASC, DESC or null if not supported by the driver
     */
    public record IndexColumn(
            @JsonProperty("name") String name,
            @JsonProperty("order") String order) {

        @JsonCreator
        public IndexColumn {
        }
    }

    /**
     * A foreign key of a table.
     *
     * @param name              constraint name
     * @param columns           referencing columns in key order
     * @param referencedSchema  schema of the referenced table
     * @param referencedTable   referenced table name
     * @param referencedColumns referenced columns, same order as columns
     * @param onUpdate          update rule: CASCADE, SET NULL, SET DEFAULT, RESTRICT or NO ACTION
     * @param onDelete          delete rule: CASCADE, SET NULL, SET DEFAULT, RESTRICT or NO ACTION
     */
    public record ForeignKey(
            @JsonProperty("name") String name,
            @JsonProperty("columns") List<String> columns,
            @JsonProperty("referencedSchema") String referencedSchema,
            @JsonProperty("referencedTable") String referencedTable,
            @JsonProperty("referencedColumns") List<String> referencedColumns,
            @JsonProperty("onUpdate") String onUpdate,
            @JsonProperty("onDelete") String onDelete) {

        @JsonCreator
        public ForeignKey {
        }
    }
}
