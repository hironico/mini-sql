package net.hironico.minisql.model.schema;

import java.sql.JDBCType;
import java.util.Locale;
import java.util.Set;

/**
 * Database flavours supported by the model import. Knows how to write column types,
 * identity columns and foreign key rules for each database.
 */
public enum SqlDialect {
    GENERIC("Generic SQL"),
    POSTGRESQL("PostgreSQL"),
    ORACLE("Oracle"),
    SQLSERVER("SQL Server"),
    SYBASE("Sybase ASE"),
    MYSQL("MySQL / MariaDB"),
    H2("H2");

    /** Native type names that never take a length, even if the driver reports a column size */
    private static final Set<String> NEVER_SIZED = Set.of(
            "uniqueidentifier", "text", "ntext", "unitext", "image", "xml", "bytea", "uuid", "json", "jsonb",
            "sysname", "timestamp", "rowversion", "tinytext", "mediumtext", "longtext", "tinyblob", "mediumblob",
            "longblob", "blob", "clob", "nclob", "long", "long raw", "inet", "cidr", "macaddr", "money",
            "smallmoney", "bit", "bool", "boolean", "date", "datetime", "smalldatetime", "character large object",
            "binary large object", "national character large object");

    private final String label;

    SqlDialect(String label) {
        this.label = label;
    }

    @Override
    public String toString() {
        return label;
    }

    /**
     * Detects the dialect from the JDBC database product name.
     *
     * @param productName value of DatabaseMetaData.getDatabaseProductName(), may be null
     * @return the matching dialect, GENERIC if unknown
     */
    public static SqlDialect detect(String productName) {
        String p = productName == null ? "" : productName.toLowerCase(Locale.ROOT);
        if (p.contains("postgres")) {
            return POSTGRESQL;
        }
        if (p.contains("oracle")) {
            return ORACLE;
        }
        if (p.contains("microsoft") || p.contains("sql server")) {
            return SQLSERVER;
        }
        if (p.contains("adaptive server") || p.contains("sybase") || p.equals("ase")) {
            return SYBASE;
        }
        if (p.contains("mysql") || p.contains("mariadb")) {
            return MYSQL;
        }
        if (p.equals("h2") || p.startsWith("h2 ")) {
            return H2;
        }
        return GENERIC;
    }

    /** @return the clause added to an auto increment column */
    public String identityClause() {
        return switch (this) {
            case SQLSERVER -> "IDENTITY(1,1)";
            case SYBASE -> "IDENTITY";
            case MYSQL -> "AUTO_INCREMENT";
            default -> "GENERATED BY DEFAULT AS IDENTITY";
        };
    }

    /** @return true if nullable columns must say NULL explicitly (columns are NOT NULL by default on Sybase) */
    public boolean explicitNull() {
        return this == SYBASE || this == SQLSERVER;
    }

    /** @return true if the database creates an index for each foreign key by itself (H2, MySQL InnoDB) */
    public boolean autoIndexesForeignKeys() {
        return this == H2 || this == MYSQL;
    }

    /** @return true if index names can (and should) be prefixed by the schema name */
    public boolean qualifiedIndexNames() {
        return this == ORACLE || this == H2;
    }

    /** @return maximum identifier length, Oracle before 12.2 is limited to 30 characters */
    public int maxIdentifierLength() {
        return switch (this) {
            case ORACLE -> 30;
            case POSTGRESQL -> 63;
            case MYSQL -> 64;
            default -> 128;
        };
    }

    /**
     * Tells if the database supports the given ON DELETE rule.
     *
     * @param rule CASCADE, SET NULL or SET DEFAULT
     * @return true if supported
     */
    public boolean supportsDeleteRule(String rule) {
        return switch (this) {
            case ORACLE -> "CASCADE".equals(rule) || "SET NULL".equals(rule);
            case SYBASE -> false;
            default -> true;
        };
    }

    /**
     * Tells if the database supports the given ON UPDATE rule.
     *
     * @param rule CASCADE, SET NULL or SET DEFAULT
     * @return true if supported
     */
    public boolean supportsUpdateRule(String rule) {
        return this != ORACLE && this != SYBASE;
    }

    /**
     * Builds the DROP TABLE statement, dropping the referencing foreign keys when the database allows it.
     *
     * @param qualifiedName the table name, already quoted and qualified
     * @return the DROP TABLE statement
     */
    public String dropTable(String qualifiedName) {
        return switch (this) {
            case POSTGRESQL, H2 -> "DROP TABLE " + qualifiedName + " CASCADE";
            case ORACLE -> "DROP TABLE " + qualifiedName + " CASCADE CONSTRAINTS";
            default -> "DROP TABLE " + qualifiedName;
        };
    }

    /**
     * Get the JDBC type of an exported column.
     *
     * @param col the column
     * @return the JDBC type, OTHER if unknown
     */
    public static JDBCType jdbcType(SchemaModel.Column col) {
        try {
            return col.jdbcType() == null ? JDBCType.OTHER : JDBCType.valueOf(col.jdbcType());
        } catch (IllegalArgumentException ex) {
            return JDBCType.OTHER;
        }
    }

    /**
     * Get the SQL type of a column for this (target) dialect. If the model comes from the same kind
     * of database, the native type is reused with its length/precision. Otherwise the portable JDBC
     * type is mapped to the closest type of this dialect.
     *
     * @param col    the exported column
     * @param source dialect of the database the model was exported from
     * @return the SQL type to use in CREATE TABLE
     */
    public String columnType(SchemaModel.Column col, SqlDialect source) {
        String nativeType = nativeTypeName(col);
        if (source == this && this != GENERIC && nativeType != null && !nativeType.isBlank()) {
            return withSize(nativeType, col);
        }
        return portableType(col, nativeType);
    }

    /**
     * Get the native type name without the " identity" suffix added by some drivers (JTDS: "int identity").
     *
     * @param col the column
     * @return the cleaned type name, may be null
     */
    public static String nativeTypeName(SchemaModel.Column col) {
        return col.type() == null ? null : col.type().trim().replaceFirst("(?i)\\s+identity$", "");
    }

    /** @return true for PostgreSQL serial types that already carry their own sequence */
    public static boolean isSerialType(String nativeType) {
        String t = nativeType == null ? "" : nativeType.toLowerCase(Locale.ROOT);
        return t.equals("serial") || t.equals("bigserial") || t.equals("smallserial")
                || t.equals("serial4") || t.equals("serial8") || t.equals("serial2");
    }

    private String withSize(String nativeType, SchemaModel.Column col) {
        if (nativeType.contains("(") || NEVER_SIZED.contains(nativeType.toLowerCase(Locale.ROOT))) {
            return nativeType;
        }
        int size = col.size() == null ? 0 : col.size();
        int scale = col.scale() == null ? 0 : col.scale();
        return switch (jdbcType(col)) {
            case CHAR, VARCHAR, NCHAR, NVARCHAR, BINARY, VARBINARY -> {
                if (size <= 0) {
                    yield nativeType;
                }
                if (size >= 1_073_741_823) {
                    // unbounded column (varchar(max), text...)
                    yield this == SQLSERVER ? nativeType + "(MAX)" : nativeType;
                }
                yield nativeType + "(" + size + ")";
            }
            case NUMERIC, DECIMAL -> {
                if (size <= 0 || size > 1000 || scale < 0) {
                    yield nativeType;
                }
                yield nativeType + "(" + size + (scale > 0 ? "," + scale : "") + ")";
            }
            default -> nativeType;
        };
    }

    private String portableType(SchemaModel.Column col, String nativeType) {
        int size = col.size() == null ? 0 : col.size();
        int scale = col.scale() == null ? 0 : col.scale();
        boolean unbounded = size <= 0 || size >= 1_073_741_823;

        return switch (jdbcType(col)) {
            case BIT, BOOLEAN -> switch (this) {
                case ORACLE -> "NUMBER(1)";
                case SQLSERVER, SYBASE -> "BIT";
                default -> "BOOLEAN";
            };
            case TINYINT -> this == ORACLE ? "NUMBER(3)" : this == POSTGRESQL ? "SMALLINT" : "TINYINT";
            case SMALLINT -> this == ORACLE ? "NUMBER(5)" : "SMALLINT";
            case INTEGER -> this == ORACLE ? "NUMBER(10)" : "INTEGER";
            case BIGINT -> this == ORACLE ? "NUMBER(19)" : "BIGINT";
            case REAL, FLOAT -> this == ORACLE ? "BINARY_FLOAT" : "REAL";
            case DOUBLE -> switch (this) {
                case ORACLE -> "BINARY_DOUBLE";
                case SQLSERVER, SYBASE -> "FLOAT";
                case MYSQL -> "DOUBLE";
                default -> "DOUBLE PRECISION";
            };
            case NUMERIC, DECIMAL -> numeric(size, scale);
            case CHAR, NCHAR -> unbounded ? text() : (this == ORACLE ? "CHAR(" + Math.min(size, 2000) + ")" : "CHAR(" + size + ")");
            case VARCHAR, NVARCHAR -> varchar(size, unbounded);
            case LONGVARCHAR, LONGNVARCHAR, CLOB, NCLOB, SQLXML -> text();
            case DATE -> "DATE";
            case TIME, TIME_WITH_TIMEZONE -> switch (this) {
                case ORACLE -> "TIMESTAMP";
                default -> "TIME";
            };
            case TIMESTAMP -> switch (this) {
                case SQLSERVER -> "DATETIME2";
                case SYBASE, MYSQL -> "DATETIME";
                default -> "TIMESTAMP";
            };
            case TIMESTAMP_WITH_TIMEZONE -> switch (this) {
                case SQLSERVER -> "DATETIMEOFFSET";
                case SYBASE, MYSQL -> "DATETIME";
                default -> "TIMESTAMP WITH TIME ZONE";
            };
            case BINARY, VARBINARY -> switch (this) {
                case POSTGRESQL -> "BYTEA";
                case ORACLE -> unbounded || size > 2000 ? "BLOB" : "RAW(" + size + ")";
                case SQLSERVER -> unbounded ? "VARBINARY(MAX)" : "VARBINARY(" + size + ")";
                default -> unbounded ? blob() : "VARBINARY(" + size + ")";
            };
            case LONGVARBINARY, BLOB -> blob();
            default -> {
                // vendor specific type (uuid, json, interval...): keep the native name if any
                if (nativeType != null && !nativeType.isBlank()) {
                    yield withSize(nativeType, col);
                }
                yield varchar(size, unbounded);
            }
        };
    }

    private String numeric(int precision, int scale) {
        // Oracle NUMBER without precision, PostgreSQL numeric without precision are reported with huge sizes
        if (precision <= 0 || precision > 38) {
            return this == ORACLE ? "NUMBER" : this == POSTGRESQL ? "NUMERIC" : "DECIMAL(38,10)";
        }
        String name = this == ORACLE ? "NUMBER" : "NUMERIC";
        return name + "(" + precision + (scale > 0 ? "," + scale : "") + ")";
    }

    private String varchar(int size, boolean unbounded) {
        return switch (this) {
            case ORACLE -> unbounded || size > 4000 ? "CLOB" : "VARCHAR2(" + size + ")";
            case SQLSERVER -> unbounded || size > 8000 ? "VARCHAR(MAX)" : "VARCHAR(" + size + ")";
            case SYBASE -> unbounded || size > 16384 ? "TEXT" : "VARCHAR(" + size + ")";
            case MYSQL -> unbounded || size > 16383 ? "LONGTEXT" : "VARCHAR(" + size + ")";
            case POSTGRESQL -> unbounded ? "TEXT" : "VARCHAR(" + size + ")";
            default -> unbounded ? "CLOB" : "VARCHAR(" + size + ")";
        };
    }

    private String text() {
        return switch (this) {
            case ORACLE, H2, GENERIC -> "CLOB";
            case SQLSERVER -> "VARCHAR(MAX)";
            case MYSQL -> "LONGTEXT";
            default -> "TEXT";
        };
    }

    private String blob() {
        return switch (this) {
            case POSTGRESQL -> "BYTEA";
            case SQLSERVER -> "VARBINARY(MAX)";
            case SYBASE -> "IMAGE";
            case MYSQL -> "LONGBLOB";
            default -> "BLOB";
        };
    }
}
